"""
Terminal UI and dashboard rendering module.
Engineered for clean, human-friendly presentation with cross-platform terminal compatibility.
"""

from __future__ import annotations
import os
import sys

# Ensure proper Windows console initialization (fixes raw escape codes like <-[1;36m in cmd.exe)
if sys.platform == "win32":
    try:
        import colorama
        colorama.just_fix_windows_console()
    except Exception:
        pass
    try:
        os.system("")  # Activates VT100 / Virtual Terminal Processing in Windows cmd.exe
    except Exception:
        pass
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")

from rich.console import Console
from rich.panel import Panel
from rich.table import Table
from rich.text import Text
from rich import box

from .analyzer import AnalysisReport, Verdict

# Fixed width for consistent, clean layout on all terminals
console = Console(width=84, highlight=False)


def render_banner() -> None:
    """Renders a clean, modern header."""
    header = Text()
    header.append("==================================================================================\n", style="bold cyan")
    header.append("   AI IMAGE DETECTOR  v1.0   *   Content Credentials & Forensics Suite\n", style="bold bright_white")
    header.append("==================================================================================", style="bold cyan")
    console.print(header)


def render_report(report: AnalysisReport, verbose: bool = False) -> None:
    """Renders an intuitive, user-friendly inspection dashboard."""
    render_banner()

    # 1. Main Verdict Card
    _render_verdict_card(report)

    # 2. Origin & Provenance (C2PA)
    if report.c2pa_result and report.c2pa_result.has_c2pa:
        _render_provenance_card(report)

    # 3. Generation Metadata & Prompts (if any found)
    if report.metadata_result and (report.metadata_result.has_ai_metadata or report.metadata_result.has_camera_exif):
        _render_metadata_card(report)

    # 4. Forensic Signals (Human-friendly summary, detailed if verbose)
    if report.forensic_result:
        _render_forensics_card(report, verbose)

    # 5. Quick action hints
    _render_footer(report)


def _render_verdict_card(report: AnalysisReport) -> None:
    f_info = report.file_info
    verdict = report.verdict
    conf = report.confidence

    # Map verdict to friendly badges and colors
    if verdict in [Verdict.CONFIRMED_AI_PROVENANCE, Verdict.CONFIRMED_AI_METADATA]:
        badge = "[bold white on red]  AI GENERATED (CONFIRMED)  [/]"
        border_col = "red"
        status_text = "[bold red]Confirmed AI-Generated Media[/]"
    elif verdict == Verdict.HIGH_PROBABILITY_AI:
        badge = "[bold white on dark_red]  HIGH PROBABILITY AI  [/]"
        border_col = "red"
        status_text = "[bold red]Strong synthetic patterns detected[/]"
    elif verdict == Verdict.SUSPICIOUS_AI:
        badge = "[bold black on yellow]  SUSPICIOUS / LIKELY AI  [/]"
        border_col = "yellow"
        status_text = "[bold yellow]Irregular synthetic signals found[/]"
    elif verdict in [Verdict.LIKELY_AUTHENTIC_CAMERA, Verdict.AUTHENTIC_VERIFIED_CAMERA]:
        badge = "[bold white on green]  AUTHENTIC PHOTO  [/]"
        border_col = "green"
        status_text = "[bold green]Authentic camera capture[/]"
    else:
        badge = "[bold black on bright_white]  INCONCLUSIVE  [/]"
        border_col = "blue"
        status_text = "[dim]Metadata absent, forensic signals ambiguous[/]"

    # Progress bar (20 chars)
    bar_len = 20
    filled = max(0, min(bar_len, int((conf / 100.0) * bar_len)))
    prog_bar = ("#" * filled) + ("-" * (bar_len - filled))

    grid = Table.grid(padding=(0, 2))
    grid.add_column(style="bold bright_cyan", justify="right", width=16)
    grid.add_column(style="white")

    grid.add_row("Target File:", f"[bold]{f_info.file_name}[/] [dim]({f_info.dimensions} · {f_info.format} · {f_info.file_size_human})[/]")
    grid.add_row("Verdict:", f"{badge}  {status_text}")
    grid.add_row("Confidence:", f"[bold bright_yellow]{conf:.1f}%[/] [{border_col}][{prog_bar}][/]")

    if report.detected_generator:
        grid.add_row("Generated By:", f"[bold bright_magenta]{report.detected_generator}[/]")

    grid.add_row("Primary Reason:", f"{report.primary_indicator}")

    console.print(Panel(grid, title="[bold]VERDICT & SUMMARY[/]", border_style=border_col, box=box.ROUNDED))


def _render_provenance_card(report: AnalysisReport) -> None:
    c = report.c2pa_result
    if not c:
        return

    grid = Table.grid(padding=(0, 2))
    grid.add_column(style="bold magenta", justify="right", width=18)
    grid.add_column(style="white")

    if c.claim_generator:
        grid.add_row("Media Engine:", c.claim_generator)
    if c.issuer:
        grid.add_row("Signed Authority:", f"[bold]{c.issuer}[/] [dim]({c.common_name or ''})[/]")
    if c.signature_time:
        grid.add_row("Created Time:", c.signature_time)

    for act in c.actions:
        sw = f"{act.software_name or ''} {act.software_version or ''}".strip()
        desc = f"[bold]{act.action}[/]"
        if sw:
            desc += f" via [cyan]{sw}[/]"
        if act.digital_source_label:
            desc += f" -> [yellow]{act.digital_source_label}[/]"
        grid.add_row("Audit Action:", desc)

    if c.watermarks:
        grid.add_row("Watermarks:", f"[bright_yellow]{', '.join(c.watermarks)}[/] [dim](Cryptographic watermark detected)[/]")

    console.print(Panel(grid, title="[bold magenta]ORIGIN & CONTENT CREDENTIALS (C2PA)[/]", border_style="magenta", box=box.ROUNDED))


def _render_metadata_card(report: AnalysisReport) -> None:
    m = report.metadata_result
    if not m:
        return

    # Generation Prompt & Parameters
    if m.has_ai_metadata:
        grid = Table.grid(padding=(0, 2))
        grid.add_column(style="bold green", justify="right", width=16)
        grid.add_column(style="white")

        if m.detected_generator:
            grid.add_row("Generator Tool:", f"[bold cyan]{m.detected_generator}[/]")
        if m.prompt:
            grid.add_row("Prompt:", f'[italic bright_white]"{m.prompt}"[/]')
        if m.negative_prompt:
            grid.add_row("Negative Prompt:", f'[dim]"{m.negative_prompt}"[/]')
        if m.model:
            grid.add_row("Model Checkpoint:", m.model)

        settings = []
        if m.steps:
            settings.append(f"Steps: {m.steps}")
        if m.sampler:
            settings.append(f"Sampler: {m.sampler}")
        if m.cfg_scale:
            settings.append(f"CFG: {m.cfg_scale}")
        if m.seed is not None:
            settings.append(f"Seed: {m.seed}")

        if settings:
            grid.add_row("Generation Settings:", " · ".join(settings))

        console.print(Panel(grid, title="[bold green]EXTRACTED PROMPT & GENERATION DATA[/]", border_style="green", box=box.ROUNDED))

    # Camera hardware EXIF
    if m.has_camera_exif:
        cam_grid = Table.grid(padding=(0, 2))
        cam_grid.add_column(style="bold green", justify="right", width=16)
        cam_grid.add_column(style="white")

        cam_name = f"{m.camera_make or ''} {m.camera_model or ''}".strip()
        cam_grid.add_row("Camera Hardware:", f"[bold]{cam_name}[/]")
        if m.lens_model:
            cam_grid.add_row("Lens Model:", m.lens_model)

        expos = []
        if m.exposure_time:
            expos.append(m.exposure_time)
        if m.f_number:
            expos.append(m.f_number)
        if m.iso_speed:
            expos.append(m.iso_speed)
        if expos:
            cam_grid.add_row("Shot Settings:", " · ".join(expos))

        console.print(Panel(cam_grid, title="[bold green]CAMERA HARDWARE EVIDENCE[/]", border_style="green", box=box.ROUNDED))


def _render_forensics_card(report: AnalysisReport, verbose: bool = False) -> None:
    f = report.forensic_result
    if not f:
        return

    score_pct = int(f.forensic_score * 100)
    score_col = "red" if score_pct >= 60 else ("yellow" if score_pct >= 35 else "green")

    table = Table(box=box.SIMPLE, show_header=True, header_style="bold cyan", padding=(0, 2))
    table.add_column("Forensic Check", style="bright_white", width=22)
    table.add_column("Status", width=24)
    table.add_column("Plain English Explanation", style="dim", width=34)

    # 1. Texture Smoothness
    if f.smoothness_ratio > 0.35:
        table.add_row(
            "Texture & Skin",
            "[bold red]Synthetic Smoothing[/]",
            "Severe lack of natural micro-texture"
        )
    elif f.smoothness_ratio > 0.20:
        table.add_row(
            "Texture & Skin",
            "[yellow]Smooth Surfaces[/]",
            "Moderate airbrushing detected"
        )
    else:
        table.add_row(
            "Texture & Skin",
            "[green]Natural Detail[/]",
            "Normal physical texture present"
        )

    # 2. Noise Distribution
    if f.noise_kurtosis > 20.0:
        table.add_row(
            "Noise Distribution",
            "[bold red]Heavy-Tail Anomaly[/]",
            "Non-sensor noise (diffusion residue)"
        )
    elif f.noise_kurtosis > 10.0:
        table.add_row(
            "Noise Distribution",
            "[yellow]Elevated Noise[/]",
            "Noise departs from physical sensors"
        )
    else:
        table.add_row(
            "Noise Distribution",
            "[green]Natural Sensor Noise[/]",
            "Matches physical camera sensors"
        )

    # 3. Frequency Decay
    if f.psd_slope < -2.9:
        table.add_row(
            "Frequency Spectrum",
            "[bold red]Abnormal Rolloff[/]",
            "High-frequency decay is unnaturally steep"
        )
    elif f.psd_slope > -1.5 and f.psd_slope != 0.0:
        table.add_row(
            "Frequency Spectrum",
            "[bold red]Synthetic Noise Tail[/]",
            "Artificial high-frequency energy"
        )
    else:
        table.add_row(
            "Frequency Spectrum",
            "[green]Natural Power-Law[/]",
            "Conforms to optical physics (1/f^2)"
        )

    # 4. Neural Grid Check
    if f.spectral_grid_score > 7.0:
        table.add_row(
            "Neural Grid Check",
            "[bold red]Grid Artifacts Flagged[/]",
            "Periodic upscaler / latent grid traces"
        )
    else:
        table.add_row(
            "Neural Grid Check",
            "[green]Clean Spectrum[/]",
            "No periodic deconvolution artifacts"
        )

    # If verbose mode: include exact technical measurements
    if verbose:
        table.add_row(
            "[dim]-- Technical Math --[/]",
            f"[dim]Kurtosis: {f.noise_kurtosis:.2f}[/]",
            f"[dim]Slope: {f.psd_slope:.3f} | Peaks: {f.spectral_grid_score:.1f}[/]"
        )

    title = f"[bold cyan]PIXEL & SIGNAL FORENSICS[/] [dim](Anomaly: [{score_col}]{score_pct}%[/])[/]"
    console.print(Panel(table, title=title, border_style="cyan", box=box.ROUNDED))


def _render_footer(report: AnalysisReport) -> None:
    tips = Text()
    tips.append("  [Tip] Need diagnostic heatmaps? ", style="dim")
    tips.append("Run with ", style="dim")
    tips.append("--save-forensics diagnostic.png", style="bold cyan")
    tips.append(" to visualize FFT & noise maps.\n", style="dim")
    console.print(tips)

